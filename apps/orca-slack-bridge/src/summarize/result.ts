import type { SummaryDraft, SummaryFacts } from './contract.js';
import { factsFingerprint } from './fingerprint.js';
import { deriveRisk, type Risk } from './validate.js';

/** The renderer-facing result is intentionally independent from every model provider module. */
export type SummaryResult =
  | {
      readonly kind: 'ok';
      readonly draft: SummaryDraft;
      readonly risk: Risk | null;
      readonly truncated: boolean;
      readonly fingerprint: string;
    }
  | {
      readonly kind: 'failed';
      readonly reason: string;
      readonly risk: Risk | null;
      readonly fingerprint: string;
    };

export interface SummaryCache {
  get(fingerprint: string): SummaryResult | undefined;
  set(fingerprint: string, result: SummaryResult): void;
}

export class MemorySummaryCache implements SummaryCache {
  private readonly map = new Map<string, SummaryResult>();
  get(fingerprint: string): SummaryResult | undefined {
    return this.map.get(fingerprint);
  }
  set(fingerprint: string, result: SummaryResult): void {
    this.map.set(fingerprint, result);
  }
}

type PersistedSummary = {
  readonly title: string;
  readonly what: string;
  readonly why: string;
  readonly reviewGist: string | null;
  readonly risk: Risk | null;
  readonly truncated: boolean;
};

export function serializeSummary(result: SummaryResult): string | null {
  if (result.kind !== 'ok') return null;
  const persisted: PersistedSummary = {
    title: result.draft.title,
    what: result.draft.what,
    why: result.draft.why,
    reviewGist: result.draft.reviewGist,
    risk: result.risk,
    truncated: result.truncated,
  };
  return JSON.stringify(persisted);
}

export function parseSummary(json: string | null, fingerprint: string): SummaryResult | null {
  if (json === null) return null;
  let raw: unknown;
  try {
    raw = JSON.parse(json);
  } catch {
    return null;
  }
  if (typeof raw !== 'object' || raw === null) return null;
  const value = raw as Record<string, unknown>;
  if (typeof value['title'] !== 'string' || typeof value['what'] !== 'string' ||
      typeof value['why'] !== 'string' ||
      (value['reviewGist'] !== null && typeof value['reviewGist'] !== 'string') ||
      (value['risk'] !== null && !isRisk(value['risk'])) ||
      typeof value['truncated'] !== 'boolean') {
    return null;
  }
  return {
    kind: 'ok',
    draft: {
      title: value['title'],
      what: value['what'],
      why: value['why'],
      reviewGist: value['reviewGist'],
    },
    risk: value['risk'],
    truncated: value['truncated'],
    fingerprint,
  };
}

function isRisk(value: unknown): value is Risk {
  return value === 'high' || value === 'medium' || value === 'low';
}

/**
 * Daemon-only deterministic fallback. It derives the reviewer risk badge from observed facts but
 * contains no prose generated by, cached from, or imported through a model provider.
 */
export function factsOnlySummary(facts: SummaryFacts): SummaryResult {
  return {
    kind: 'failed',
    reason: 'daemon facts-only mode',
    risk: deriveRisk(facts),
    fingerprint: factsFingerprint(facts),
  };
}
